// Usage: tsx src/gold-cli.ts [--per-sector 3]
// Picks the gold set (the companies a person scores by hand, blind to the AI draft) from the real-data database and
// writes it to packages/shared/src/gold-set.ts. The same list is the fixed universe of the research study.
import { parseArgs } from "node:util";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { sql } from "drizzle-orm";
import { createDb } from "@portfolio-lab/db";
import { pickGoldSet } from "./gold";

const { values } = parseArgs({ options: { "per-sector": { type: "string", default: "3" } } });
const url = process.env.DATABASE_URL;
if (!url) throw new Error("DATABASE_URL is required");
const { db, close } = createDb(url);

const rows = await db.execute<{
  ticker: string;
  sector: string | null;
  cik: string | null;
  dv: number | null;
}>(sql`
  select c.ticker, c.sector, c.cik,
    percentile_cont(0.5) within group (order by p.close * p.volume) as dv
  from companies c
  join prices_daily p on p.company_id = c.id
  where p.date > (select max(date) from prices_daily) - interval '365 days' and p.volume is not null
  group by c.ticker, c.sector, c.cik`);
const tickers = pickGoldSet(
  rows.map((r) => ({
    ticker: r.ticker,
    sector: r.sector,
    issuer: r.cik,
    dollarVolume: Number(r.dv ?? 0),
  })),
  Number(values["per-sector"]),
);
await close();

const file = fileURLToPath(new URL("../../shared/src/gold-set.ts", import.meta.url));
const today = new Date().toISOString().slice(0, 10);
await writeFile(
  file,
  `// Generated by \`pnpm data:gold\` on ${today}. Do not edit by hand: the paper and the study refer to this exact list.
// The ${values["per-sector"]} most traded S&P 500 companies in each sector (median daily traded value over the last year),
// one share class per issuer.

/** Companies a person scores by hand, without seeing the AI draft, to measure how far the drafts can be trusted. */
export const GOLD_SET: readonly string[] = ${JSON.stringify(tickers, null, 2)};

export function isGold(ticker: string): boolean {
  return GOLD_SET.includes(ticker.toUpperCase());
}
`,
);
console.log(`wrote ${tickers.length} tickers to ${file}`);
console.log(tickers.join(","));
